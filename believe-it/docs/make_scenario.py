def H(t, l=1): doc.add_heading(t, level=l)
def P(t, b=False, i=False, c=None):
    p = doc.add_paragraph(); r = p.add_run(t); r.bold = b; r.italic = i
    if c: r.font.color.rgb = RGBColor(*c)
    return p
def L(items):
    for t in items: doc.add_paragraph(t, style='List Bullet')
def Q(t):  # on-screen text
    p = doc.add_paragraph(); r = p.add_run(t); r.italic = True; r.font.color.rgb = RGBColor(0x55, 0x3a, 0x22)
    p.paragraph_format.left_indent = Cm(0.8)
def table(rows, head, w=None):
    t = doc.add_table(rows=1, cols=len(head)); t.style = 'Light Grid Accent 1'
    for i, h in enumerate(head): t.rows[0].cells[i].text = h
    for r in rows:
        cells = t.add_row().cells
        for i, v in enumerate(r): cells[i].text = v
    if w:
        for row in t.rows:
            for i, x in enumerate(w): row.cells[i].width = Cm(x)
    doc.add_paragraph()

