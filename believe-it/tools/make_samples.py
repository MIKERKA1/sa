# packs assets_src/clips/*.mp3 into src/farm/samples.js (base64). Source recordings: BigSoundBank.com (Joseph Sardin), CC0.
import base64, glob, os, re, collections
B = collections.OrderedDict()
for p in sorted(glob.glob('assets_src/clips/*.mp3')):
    k = re.sub(r'\d+$', '', os.path.basename(p)[:-4]); B.setdefault(k, []).append(base64.b64encode(open(p, 'rb').read()).decode())
with open('src/farm/samples.js', 'w') as f:
    f.write('// Animal recordings (mono mp3, 22 kHz), cut from BigSoundBank.com by Joseph Sardin, released CC0 (public domain).\n')
    f.write('// Generated by tools/make_samples.py from assets_src/clips — do not edit by hand.\n')
    f.write('export const SAMPLES = {\n')
    for k, L in B.items(): f.write(f"  {k}: [{', '.join(repr(x) for x in L)}],\n")
    f.write('};\n')
print({k: len(v) for k, v in B.items()}, os.path.getsize('src/farm/samples.js'))
